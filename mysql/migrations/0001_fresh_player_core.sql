CREATE TABLE users (
  id CHAR(36) NOT NULL,
  email VARCHAR(320) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(32) NULL,
  full_name VARCHAR(160) NOT NULL,
  avatar_url TEXT NULL,
  date_of_birth DATE NULL,
  gender VARCHAR(32) NULL,
  city_id CHAR(36) NULL,
  timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Makassar',
  locale VARCHAR(16) NOT NULL DEFAULT 'id',
  is_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email),
  KEY idx_users_city_id (city_id),
  CONSTRAINT fk_users_city FOREIGN KEY (city_id) REFERENCES cities (id) ON DELETE SET NULL,
  CONSTRAINT chk_users_gender CHECK (gender IS NULL OR gender IN ('male', 'female', 'other', 'prefer_not_to_say'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE tennis_courts (
  id CHAR(36) NOT NULL,
  name VARCHAR(160) NOT NULL,
  city_id CHAR(36) NOT NULL,
  address VARCHAR(500) NOT NULL,
  court_type VARCHAR(64) NOT NULL DEFAULT 'hard',
  number_of_courts INT NOT NULL DEFAULT 1,
  environment VARCHAR(64) NOT NULL DEFAULT 'outdoor',
  status VARCHAR(32) NOT NULL DEFAULT 'active',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_tennis_courts_city_id (city_id),
  CONSTRAINT fk_tennis_courts_city FOREIGN KEY (city_id) REFERENCES cities (id),
  CONSTRAINT chk_tennis_courts_count CHECK (number_of_courts > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE player_profiles (
  id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  display_name VARCHAR(160) NULL,
  bio TEXT NULL,
  playing_since VARCHAR(32) NULL,
  preferred_hand VARCHAR(16) NULL,
  backhand VARCHAR(16) NULL,
  preferred_court_id CHAR(36) NULL,
  play_frequency VARCHAR(32) NULL,
  preferred_categories JSON NULL,
  preferred_times JSON NULL,
  self_assessed_level VARCHAR(32) NULL,
  ntrp_rating DECIMAL(4, 2) NULL,
  itf_wtn DECIMAL(4, 2) NULL,
  usta_rating DECIMAL(4, 2) NULL,
  is_profile_public BOOLEAN NOT NULL DEFAULT TRUE,
  profile_visibility VARCHAR(32) NOT NULL DEFAULT 'public',
  show_rating BOOLEAN NOT NULL DEFAULT TRUE,
  show_history BOOLEAN NOT NULL DEFAULT TRUE,
  show_online_status BOOLEAN NOT NULL DEFAULT TRUE,
  allow_invites BOOLEAN NOT NULL DEFAULT TRUE,
  completion_score INT NOT NULL DEFAULT 40,
  is_verified_player BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_player_profiles_user_id (user_id),
  KEY idx_player_profiles_public (is_profile_public, profile_visibility),
  KEY idx_player_profiles_preferred_court (preferred_court_id),
  CONSTRAINT fk_player_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_player_profiles_preferred_court FOREIGN KEY (preferred_court_id) REFERENCES tennis_courts (id) ON DELETE SET NULL,
  CONSTRAINT chk_player_profiles_hand CHECK (preferred_hand IS NULL OR preferred_hand IN ('right', 'left')),
  CONSTRAINT chk_player_profiles_backhand CHECK (backhand IS NULL OR backhand IN ('one_handed', 'two_handed')),
  CONSTRAINT chk_player_profiles_frequency CHECK (play_frequency IS NULL OR play_frequency IN ('daily', 'weekly', 'biweekly', 'monthly', 'occasional')),
  CONSTRAINT chk_player_profiles_level CHECK (self_assessed_level IS NULL OR self_assessed_level IN ('beginner', 'intermediate', 'advanced')),
  CONSTRAINT chk_player_profiles_visibility CHECK (profile_visibility IN ('public', 'friends_only', 'private')),
  CONSTRAINT chk_player_profiles_completion CHECK (completion_score BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE player_ratings (
  id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  current_rating DECIMAL(4, 2) NOT NULL DEFAULT 1.00,
  peak_rating DECIMAL(4, 2) NOT NULL DEFAULT 1.00,
  matches_played INT NOT NULL DEFAULT 0,
  wins INT NOT NULL DEFAULT 0,
  losses INT NOT NULL DEFAULT 0,
  draws INT NOT NULL DEFAULT 0,
  win_streak INT NOT NULL DEFAULT 0,
  best_win_streak INT NOT NULL DEFAULT 0,
  current_streak_type VARCHAR(16) NOT NULL DEFAULT 'none',
  last_match_at TIMESTAMP NULL,
  last_rating_change_at TIMESTAMP NULL,
  rating_algorithm_version INT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_player_ratings_user_id (user_id),
  KEY idx_player_ratings_current_rating (current_rating),
  CONSTRAINT fk_player_ratings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT chk_player_ratings_current CHECK (current_rating BETWEEN 1.00 AND 10.00),
  CONSTRAINT chk_player_ratings_peak CHECK (peak_rating BETWEEN 1.00 AND 10.00),
  CONSTRAINT chk_player_ratings_counts CHECK (matches_played >= 0 AND wins >= 0 AND losses >= 0 AND draws >= 0),
  CONSTRAINT chk_player_ratings_streaks CHECK (win_streak >= 0 AND best_win_streak >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
