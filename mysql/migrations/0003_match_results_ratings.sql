CREATE TABLE match_results (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  team1_score INT NOT NULL,
  team2_score INT NOT NULL,
  winner_team TINYINT NOT NULL,
  submitted_by CHAR(36) NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmed_at TIMESTAMP NULL,
  disputed_at TIMESTAMP NULL,
  is_walkover BOOLEAN NOT NULL DEFAULT FALSE,
  walkover_by CHAR(36) NULL,
  walkover_reason TEXT NULL,
  metadata JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_match_results_match_id (match_id),
  KEY idx_match_results_status_submitted (status, submitted_at),
  CONSTRAINT fk_match_results_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT fk_match_results_submitted_by FOREIGN KEY (submitted_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_match_results_walkover_by FOREIGN KEY (walkover_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_match_results_scores CHECK (team1_score >= 0 AND team2_score >= 0),
  CONSTRAINT chk_match_results_winner CHECK (winner_team IN (1, 2)),
  CONSTRAINT chk_match_results_status CHECK (status IN ('pending', 'confirmed', 'disputed', 'under_review'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE rating_history (
  id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  old_rating DECIMAL(4, 2) NOT NULL,
  new_rating DECIMAL(4, 2) NOT NULL,
  rating_change DECIMAL(5, 2) GENERATED ALWAYS AS (new_rating - old_rating) STORED,
  change_reason VARCHAR(50) NOT NULL,
  match_result VARCHAR(16) NOT NULL,
  opponent_id CHAR(36) NULL,
  opponent_rating DECIMAL(4, 2) NULL,
  algorithm_version INT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rating_history_match_user (match_id, user_id),
  KEY idx_rating_history_user_created (user_id, created_at),
  CONSTRAINT fk_rating_history_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_rating_history_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE RESTRICT,
  CONSTRAINT fk_rating_history_opponent FOREIGN KEY (opponent_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_rating_history_old CHECK (old_rating BETWEEN 1.00 AND 10.00),
  CONSTRAINT chk_rating_history_new CHECK (new_rating BETWEEN 1.00 AND 10.00),
  CONSTRAINT chk_rating_history_opponent CHECK (
    opponent_rating IS NULL OR opponent_rating BETWEEN 1.00 AND 10.00
  ),
  CONSTRAINT chk_rating_history_result CHECK (match_result IN ('win', 'loss', 'draw'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
